/**
 * @file lib/ai/sqlAgent.ts
 *
 * Natural-language → SQL → plain-English answer agent for the analytics page.
 *
 * Professors can type free-form questions ("Which students submitted the most
 * questions this semester?") and get a readable answer derived from actual DB data.
 * This module implements the two-step pipeline:
 *   1. Gemini generates a SELECT query from the question + schema context
 *   2. The query runs against Supabase via the `execute_analytics_query` RPC
 *   3. Gemini converts the raw rows into a plain-English answer for the professor
 *
 * ## Security model
 * - Client-side regex guard (`assertReadOnly`) blocks obvious write keywords before
 *   the query reaches the database
 * - The `execute_analytics_query` Postgres function (SECURITY DEFINER) performs a
 *   second server-side validation and only allows SELECT statements
 * - The admin client is used for the RPC call because `execute_analytics_query`
 *   bypasses RLS by design (professors need read access across their data)
 *
 * ## Where it fits
 * - Called by: app/api/analytics/query/route.ts
 * - Uses: lib/ai/geminiClient.ts, lib/supabase/server.ts (admin client)
 * - The `execute_analytics_query` SQL function must exist in Supabase before
 *   this module can operate
 */

import { getGeminiClient, getGeminiModel } from '@/lib/ai/geminiClient'
import { createAdminClient } from '@/lib/supabase/server'

// ---------------------------------------------------------------------------
// Read-only SQL guard (client-side; DB fn also validates)
// ---------------------------------------------------------------------------

/**
 * Regex matching any SQL keyword that could modify data or schema.
 * Tested against the raw SQL string before it is sent to the database.
 * This is a defence-in-depth check — the DB-level RPC also validates.
 */
/**
 * Regex matching any SQL keyword that could modify data or schema.
 *
 * What it does: Defines a regular expression to identify SQL keywords that perform write operations or Data Definition Language (DDL) commands.
 * Why it is used: To implement a crucial client-side safety check. This regex helps prevent the accidental or malicious execution of non-SELECT queries before they even reach the database, serving as a primary defense-in-depth mechanism that complements server-side validation.
 * Important implementation details: It uses word boundaries (`\b`) to ensure whole keywords are matched and is case-insensitive (`i` flag) to catch variations like 'insert' or 'UPDATE'. It covers common DML (INSERT, UPDATE, DELETE, COPY) and DDL (DROP, CREATE, ALTER, TRUNCATE, GRANT, REVOKE) commands.
 */
const WRITE_KEYWORDS = /\b(INSERT|UPDATE|DELETE|DROP|CREATE|ALTER|TRUNCATE|GRANT|REVOKE|COPY)\b/i

/**
 * Throws if the generated SQL contains any write or DDL keywords.
 *
 * This client-side check runs before the query reaches Supabase, providing an
 * early rejection that produces a more informative error message than what the
 * database function would return. The DB function also validates — this is not
 * the only guard.
 *
 * @param sql - The raw SQL string generated by Gemini
 * @throws Error if any disallowed keyword is found
 */
/**
 * Throws if the generated SQL contains any write or DDL keywords.
 *
 * What it does: Validates a given SQL string to ensure it strictly contains only read-only operations (i.e., SELECT queries).
 * Why it is used: This client-side check runs before the query is sent to the Supabase database. It provides an early rejection point, producing a more immediate and informative error message to the user or developer than a generic database error would. This functions as a vital defense-in-depth layer; while the database-level RPC also validates the query, this client-side guard offers enhanced user experience and pre-empts potentially unsafe queries.
 * Important implementation details: It leverages the `WRITE_KEYWORDS` regular expression. If `WRITE_KEYWORDS.test(sql)` returns true, indicating a prohibited keyword, an `Error` is thrown with a descriptive message specific to analytics queries.
 */
function assertReadOnly(sql: string): void {
  if (WRITE_KEYWORDS.test(sql)) {
    throw new Error('Only SELECT queries are permitted in analytics.')
  }
}

