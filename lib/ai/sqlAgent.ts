/**
 * Static schema description injected into every SQL-generation prompt.
 *
 * This gives Gemini the table and column definitions it needs to write correct
 * JOIN conditions, filter expressions, and aliases. Kept deliberately minimal —
 * only the four tables relevant to analytics queries are described.
 *
 * Important notes embedded in the schema:
 * - `student_name` is stored in "FirstName L." format (partial name matching guidance)
 * - `semester_id = NULL` means the session is unassigned
 * - `theme_number` is 1-based within a session
 */
/**
 * Static schema description injected into every SQL-generation prompt.
 *
 * What it does: Provides a concise, static description of the relevant PostgreSQL database schema, including table and column definitions.
 * Why it is used: To furnish the Gemini AI model with the essential structural context it needs to accurately generate SQL queries from natural language questions. This schema description enables Gemini to understand table relationships, column types, and specific data formats, which is crucial for writing correct JOIN conditions, filter expressions, and appropriate aliases.
 * Important implementation details: The schema is deliberately kept minimal, describing only the four tables (`semesters`, `sessions`, `student_submissions`, `session_themes`) that are pertinent to analytics queries. Important domain-specific notes and rules are embedded within the description, such as the `student_name` format ("FirstName L."), the meaning of `semester_id = NULL` (unassigned sessions), and the 1-based indexing of `theme_number`. Explicit rules for the AI, like "Only generate SELECT queries" and "Always qualify table names", are also included.
 */
const SCHEMA_CONTEXT = `
You have read-only access to a PostgreSQL database for a university professor tool called MGMT 305.
Professors upload student question submissions for guest speaker sessions; the AI synthesizes them.

Tables available to you:

  semesters (
    id           UUID PRIMARY KEY,
    user_id      UUID,           -- professor's user ID
    name         TEXT,           -- e.g. "Spring 2026"
    start_date   DATE,
    end_date     DATE,
    status       TEXT,           -- 'active' or 'archived'
    created_at   TIMESTAMPTZ
  )

  sessions (
    id           UUID PRIMARY KEY,
    user_id      UUID,           -- professor's user ID
    speaker_name TEXT,           -- name of the guest speaker
    created_at   TIMESTAMPTZ,
    output       TEXT,           -- full AI-generated markdown output
    file_count   INTEGER,        -- number of student files processed
    semester_id  UUID REFERENCES semesters(id)  -- nullable; NULL = unassigned to any semester
  )

  student_submissions (
    id              UUID PRIMARY KEY,
    session_id      UUID REFERENCES sessions(id),
    student_name    TEXT,         -- "FirstName L." format, e.g. "Jake M."
    submission_text TEXT,         -- raw text of what the student submitted
    created_at      TIMESTAMPTZ
  )

  session_themes (
    id           UUID PRIMARY KEY,
    session_id   UUID REFERENCES sessions(id),
    theme_number INTEGER,          -- 1-based rank
    theme_title  TEXT,             -- e.g. "Leadership Under Pressure"
    created_at   TIMESTAMPTZ
  )

Rules:
- Only generate SELECT queries. Never INSERT, UPDATE, DELETE, or DROP anything.
- Always qualify table names (e.g. sessions.id, not just id) when joining.
- Return concise, readable column aliases in result sets.
- student_name is stored as "FirstName L." — use ILIKE '%Jake%' for partial first-name matching.
- session_themes.theme_number is 1-based ordering within a session.
- sessions.semester_id links to semesters. When the user asks about a specific semester, filter by sessions.semester_id. NULL semester_id means the session is unassigned to any semester.
`.trim()

/**
 * Builds the Gemini prompt that asks the model to generate a SQL SELECT query
 * from a natural language question.
 *
 * Instructs Gemini to return only raw SQL — no markdown fences, no trailing
 * semicolon — so the result can be used directly in the `assertReadOnly` check
 * and passed to the Supabase RPC without further transformation (beyond trimming).
 *
 * @param question - The professor's free-form analytics question
 * @returns The full SQL-generation prompt
 */
/**
 * Builds the Gemini prompt that asks the model to generate a SQL SELECT query
 * from a natural language question.
 *
 * What it does: Constructs the full prompt string that will be sent to the Gemini AI model to request the generation of a SQL SELECT query.
 * Why it is used: To precisely instruct Gemini on its task. It ensures the AI receives all necessary context (database schema, specific rules) and is explicitly directed to return only the raw SQL query, without any additional markdown formatting, explanations, or trailing semicolons. This simplifies post-processing of the AI's output.
 * Important implementation details: It prepends the `SCHEMA_CONTEXT` variable to provide the AI with the foundational knowledge of the database structure and associated rules. The prompt explicitly specifies that the AI should "Generate a single, read-only SQL SELECT query" and "Respond with ONLY the raw SQL query — no markdown fences, no explanation, no trailing semicolon" to ensure clean output.
 */
function buildSqlPrompt(question: string): string {
  return `${SCHEMA_CONTEXT}

Generate a single, read-only SQL SELECT query that answers this question:
"${question}"

Respond with ONLY the raw SQL query — no markdown fences, no explanation, no trailing semicolon.`
}

/**
 * Builds the Gemini prompt that converts raw database rows into a plain-English
 * answer for the professor.
 *
 * Provides both the original question and the executed SQL as context so Gemini
 * can map column names to meaningful phrases. The prompt explicitly forbids
 * repeating SQL or internal table names in the output, keeping the answer
 * approachable for non-technical users.
 *
 * @param question - The professor's original natural language question
 * @param sql - The SQL query that was executed (for Gemini's context)
 * @param rows - The raw result rows returned by the database
 * @returns The full answer-generation prompt
 */
/**
 * Builds the Gemini prompt that converts raw database rows into a plain-English
 * answer for the professor.
 *
 * What it does: Assembles the prompt string used to instruct the Gemini AI model to transform raw database query results into a human-readable, plain-English answer.
 * Why it is used: To bridge the gap between technical database output and user understanding. This prompt allows Gemini to synthesize the executed query, its results, and the original question into an easily digestible response for a non-technical user (the professor).
 * Important implementation details: It provides three key pieces of context to Gemini: the `question` (original natural language query), the `sql` (the executed query, for contextual understanding of column names and intent), and the `rows` (the raw JSON representation of the database results). The prompt explicitly forbids Gemini from repeating the SQL query or mentioning internal table names in its output, ensuring the answer remains approachable and free of technical jargon.
 */
function buildAnswerPrompt(question: string, sql: string, rows: unknown[]): string {
  return `A professor asked: "${question}"

The following SQL was run:
${sql}

The query returned ${rows.length} row(s):
${JSON.stringify(rows, null, 2)}

Write a clear, concise plain-English answer for the professor. Use bullet points if there are multiple items. Do not repeat the SQL or mention internal table names.`
}

